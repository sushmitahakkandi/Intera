const imageFallbackMiddleware = (req, res, next) => {
  const urlPath = req.path;
  
  if (!urlPath.startsWith('/products/')) {
    return next();
  }

  // Parse path: ['products', 'sofa', 'elite-dallas-steel-leather-sofa', 'thumbnail.webp']
  const parts = urlPath.split('/').filter(Boolean);
  const categoryRaw = parts[1] ? parts[1].toLowerCase() : 'furniture';
  const nameSlug = parts[2] ? parts[2].toLowerCase() : 'item';

  const unsplashList = UNSPLASH_IDS[categoryRaw] || DEFAULT_IDS;

  // Generate a unique, deterministic hash based on the product name slug
  let hash = 0;
  for (let i = 0; i < nameSlug.length; i++) {
    hash = nameSlug.charCodeAt(i) + ((hash << 5) - hash);
  }
  const positiveHash = Math.abs(hash);

  // Pick a base Unsplash photo ID from the curated list
  const baseIndex = positiveHash % unsplashList.length;
  const photoId = unsplashList[baseIndex];

  // Map product name keywords to specific Unsplash-compatible color hue adjustments
  // This enables one base photo to render in completely different color variations!
  const colors = {
    blue: 200,
    green: 100,
    red: 330,
    pink: 325,
    yellow: 45,
    orange: 25,
    purple: 275,
    teal: 165,
    gold: 40,
    brown: 15
  };

  let hue = 0;
  let hasColor = false;
  for (const [colorName, hueVal] of Object.entries(colors)) {
    if (nameSlug.includes(colorName)) {
      hue = hueVal;
      hasColor = true;
      break;
    }
  }

  // If no explicit color is matched in the name, generate a deterministic hue to avoid repetitive look
  if (!hasColor) {
    hue = positiveHash % 360;
  }

  // Generate unique brightness/contrast/saturation tweaks based on hash to differentiate duplicates
  const bri = (positiveHash % 16) - 8;   // -8 to +7
  const con = (positiveHash % 16) - 8;   // -8 to +7
  const sat = (positiveHash % 20) - 10;  // -10 to +9

  // Build the modified Unsplash CDN URL
  const imageUrl = `https://images.unsplash.com/${photoId}?auto=format&fit=crop&w=600&h=600&q=80&hue=${hue}&bri=${bri}&con=${con}&sat=${sat}`;

  // Redirect the client browser directly to the customized, high-quality photograph
  return res.redirect(imageUrl);
};

